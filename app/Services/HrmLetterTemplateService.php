    public static function findTemplate(string $code): ?array
    {
        foreach (self::templates() as $tpl) {
            if ($tpl['code'] === $code) {
                return $tpl;
            }
        }
        return null;
    }

    public static function render(string $code, array $data): array
    {
        $tpl = self::findTemplate($code) ?? self::templates()[0];

        $replace = function (string $text) use ($data): string {
            return preg_replace_callback('/\{\{(\w+)\}\}/', function ($m) use ($data) {
                $val = $data[$m[1]] ?? '';
                return $val !== '' ? (string) $val : '[' . $m[1] . ']';
            }, $text);
        };

        $refNo = $data['reference_number'] ?? ($tpl['reference_prefix'] . '/' . date('Y') . '/' . str_pad((string) random_int(1, 999), 3, '0', STR_PAD_LEFT));

        return [
            'template' => $tpl,
            'reference_number' => $refNo,
            'subject' => $replace($tpl['subject']),
            'body' => $replace($tpl['body']),
            'date' => $data['date'] ?? date('Y-m-d'),
            'employee_name' => $data['employee_name'] ?? '',
            'employee_number' => $data['employee_number'] ?? '',
            'employee_address' => $data['employee_address'] ?? '',
            'signatory_name' => $data['signatory_name'] ?? 'Human Resources',
            'signatory_title' => $data['signatory_title'] ?? 'Mutamark Enterprises Ltd',
        ];
    }
